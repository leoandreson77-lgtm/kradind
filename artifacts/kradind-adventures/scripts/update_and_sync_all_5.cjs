const fs = require('fs');
const path = require('path');
const { MongoClient } = require('mongodb');

const scratchDir = 'C:/Users/DELL/.gemini/antigravity-ide/brain/e0f90f8b-e1dd-4c09-aac3-dfad7d46cb97/scratch';
const new5Packages = JSON.parse(fs.readFileSync(path.join(scratchDir, 'all_5_packages.json'), 'utf-8'));

const allPackagesPath = path.resolve(__dirname, '..', 'data', 'all-packages.json');
const cmsStorePath = path.resolve(__dirname, '..', 'data', 'cms-store.json');
const travelDataPath = path.resolve(__dirname, '..', 'src', 'lib', 'travel-data.ts');

const existingPackages = JSON.parse(fs.readFileSync(allPackagesPath, 'utf8'));

// Slug replacements map
const replaceSlugs = {
  'goa-tour-package': 'goa-tour-package-4-nights-5-days',
  'goa-tour-package-4-nights-5-days': 'goa-tour-package-4-nights-5-days',
  'manali-tour-package-4-nights-5-days': 'manali-tour-package-4-nights-5-days',
  'meghalaya-tour-package': 'meghalaya-tour-package-5-nights-6-days',
  'meghalaya-tour-package-5-nights-6-days': 'meghalaya-tour-package-5-nights-6-days',
  'maharashtra-tour-package': 'maharashtra-tour-package-4-nights-5-days',
  'maharashtra-tour-package-4-nights-5-days': 'maharashtra-tour-package-4-nights-5-days',
  'kerala-tour-package': 'kerala-tour-package-5-nights-6-days',
  'kerala-tour-package-5-nights-6-days': 'kerala-tour-package-5-nights-6-days',
};

// Filter existing packages and replace or add
const updatedList = [];
const newSlugsMap = new Map();
new5Packages.forEach(p => newSlugsMap.set(p.slug, p));

for (const pkg of existingPackages) {
  const targetNewSlug = replaceSlugs[pkg.slug];
  if (targetNewSlug && newSlugsMap.has(targetNewSlug)) {
    // Replace with new package object
    const newPkg = newSlugsMap.get(targetNewSlug);
    updatedList.push(newPkg);
    newSlugsMap.delete(targetNewSlug);
  } else if (!replaceSlugs[pkg.slug]) {
    updatedList.push(pkg);
  }
}

// Any remaining new packages that weren't in existing list
for (const remainingPkg of newSlugsMap.values()) {
  updatedList.push(remainingPkg);
}

console.log(`Updated packages list length: ${updatedList.length}`);

// 1. Write all-packages.json
fs.writeFileSync(allPackagesPath, JSON.stringify(updatedList, null, 2), 'utf8');
console.log('Saved data/all-packages.json');

// 2. Write cms-store.json
if (fs.existsSync(cmsStorePath)) {
  const store = JSON.parse(fs.readFileSync(cmsStorePath, 'utf8'));
  store.treks = updatedList;
  fs.writeFileSync(cmsStorePath, JSON.stringify(store, null, 2), 'utf8');
  console.log('Saved data/cms-store.json');
}

